  let _lang = localStorage.getItem('bb_lang') || null;

  // ── API pública ──────────────────────────────────────────────────────────
  function setLang(code) {
    _lang = code;
    localStorage.setItem('bb_lang', code);
    document.documentElement.lang = code === 'pt' ? 'pt-BR' : code === 'hu' ? 'hu' : 'en';
  }

  function getLang() { return _lang; }

  function t(key, ...args) {
    // Cadeia de fallback: idioma ativo → EN → PT → key literal
    const dict    = STRINGS[_lang] || {};
    const fallback = STRINGS['en'] || {};
    const base     = STRINGS['pt'] || {};
    const val = (key in dict) ? dict[key]
              : (key in fallback) ? fallback[key]
              : (key in base)     ? base[key]
              : key;
    if (typeof val === 'function') return val(...args);
    return val ?? key;
  }

  return { setLang, getLang, t };
